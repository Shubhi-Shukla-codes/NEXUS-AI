def get_icon_svg(
    name: str,
    size: int = 19,
    color: str = "currentColor",
    stroke_width: float = 2.0,
    extra_class: str = "",
    aria_label: Optional[str] = None
) -> str:
    """
    Generate clean, inline Lucide SVG markup.
    Dimensions, stroke-width, and color conform to the NEXUS design system.
    """
    icon_key = name.lower().replace("-", "_").replace(" ", "_")
    path_data = LUCIDE_PATHS.get(icon_key, LUCIDE_PATHS.get("info", ""))

    aria_attr = f'aria-label="{aria_label}" role="img"' if aria_label else 'aria-hidden="true"'
    cls_attr = f'class="nexus-lucide-icon {extra_class}".strip()'

    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round" {cls_attr} {aria_attr} '
        f'style="display:inline-block; vertical-align:middle; flex-shrink:0;">'
        f'{path_data}'
        f'</svg>'
    )


def icon_html(
    name: str,
    text: str = "",
    size: int = 19,
    color: str = "currentColor",
    stroke_width: float = 2.0,
    gap: int = 8,
    extra_class: str = "",
    position: str = "left"
) -> str:
    """
    Render icon alongside text with consistent alignment and spacing.
    """
    svg = get_icon_svg(name, size=size, color=color, stroke_width=stroke_width, extra_class=extra_class)
    if not text:
        return svg

    if position == "right":
        return (
            f'<span style="display:inline-flex; align-items:center; gap:{gap}px;">'
            f'<span>{text}</span>{svg}'
            f'</span>'
        )
    return (
        f'<span style="display:inline-flex; align-items:center; gap:{gap}px;">'
        f'{svg}<span>{text}</span>'
        f'</span>'
    )


